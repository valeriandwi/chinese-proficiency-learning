package media

import (
	"context"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

// TTSProvider turns text into audio bytes. The interface is the seam that keeps a
// cloud vendor out of the rest of the codebase.
type TTSProvider interface {
	Name() string
	Voice() string
	// Format is the container extension produced, e.g. "mp3".
	Format() string
	// Synthesize returns the encoded audio and its container extension.
	Synthesize(ctx context.Context, text string) (data []byte, format string, err error)
}

// ErrTTSUnavailable means no provider can run in this environment.
var ErrTTSUnavailable = errors.New("media: no text-to-speech provider available")

// SayProvider synthesises with macOS `say` and transcodes with ffmpeg.
//
// It is the default in development because it needs no credentials and works
// offline, which is what lets the audio pipeline be exercised (and tested) on a
// laptop. It is NOT a production choice: the licence terms that apply to
// redistributing audio generated by an operating-system voice are the vendor's,
// not ours, and they must be checked before these files are served to end users.
// See docs/sources.md — the same rule that applies to any other third-party data.
//
// A cloud provider is a second implementation of this interface, selected by
// TTS_PROVIDER once credentials exist; nothing else changes.
type SayProvider struct {
	VoiceName string
	Binary    string
	FFmpeg    string
	// AudioFormat is the container produced after transcoding.
	AudioFormat string
}

// NewSayProvider returns the macOS provider, or ErrTTSUnavailable when `say` or
// ffmpeg is missing (another platform, or a stripped container).
func NewSayProvider(voice, ffmpegPath string) (*SayProvider, error) {
	bin, err := exec.LookPath("say")
	if err != nil {
		return nil, fmt.Errorf("%w: `say` is not on PATH", ErrTTSUnavailable)
	}
	// An empty FFMPEG_PATH means "find ffmpeg on PATH". Passing the empty string
	// straight to LookPath would instead look for a program with no name and fail
	// with a confusing "not on PATH" error on a machine that has ffmpeg.
	if ffmpegPath == "" {
		ffmpegPath = "ffmpeg"
	}
	ff, err := exec.LookPath(ffmpegPath)
	if err != nil {
		return nil, fmt.Errorf("%w: ffmpeg not found (%q); set FFMPEG_PATH", ErrTTSUnavailable, ffmpegPath)
	}
	if voice == "" {
		voice = "Tingting"
	}
	p := &SayProvider{VoiceName: voice, Binary: bin, FFmpeg: ff, AudioFormat: "mp3"}
	if err := p.checkVoice(); err != nil {
		return nil, err
	}
	return p, nil
}

// checkVoice fails loudly at startup rather than per asset: an unknown voice name
// makes `say` fall back to the default (usually English) and would otherwise
// produce a library of wrong-language audio that nobody notices until a learner
// hears English read from a Chinese lesson.
func (p *SayProvider) checkVoice() error {
	out, err := exec.Command(p.Binary, "-v", "?").Output()
	if err != nil {
		return fmt.Errorf("media: listing voices: %w", err)
	}
	for _, line := range strings.Split(string(out), "\n") {
		if strings.HasPrefix(line, p.VoiceName+" ") {
			return nil
		}
	}
	return fmt.Errorf("media: voice %q is not installed (try `say -v '?' | grep zh_CN`)", p.VoiceName)
}

func (p *SayProvider) Name() string   { return "say" }
func (p *SayProvider) Voice() string  { return p.VoiceName }
func (p *SayProvider) Format() string { return p.AudioFormat }

func (p *SayProvider) Synthesize(ctx context.Context, text string) ([]byte, string, error) {
	clean := TextForAudio(text)
	if clean == "" {
		return nil, "", errors.New("media: nothing to synthesise")
	}
	dir, err := os.MkdirTemp("", "hanpath-tts-")
	if err != nil {
		return nil, "", fmt.Errorf("media: temp dir: %w", err)
	}
	defer os.RemoveAll(dir)

	aiff := filepath.Join(dir, "speech.aiff")
	out := filepath.Join(dir, "speech."+p.AudioFormat)
	// No --data-format here: this `say` build reads "=LEI16@22050" as a file name
	// and fails with "Opening output file failed". The default AIFF is exactly what
	// the transcode step wants, and ffmpeg is what normalises the sample rate and
	// channel count (-ar 22050 -ac 1) rather than the synthesiser.
	say := exec.CommandContext(ctx, p.Binary,
		"-v", p.VoiceName,
		"-o", aiff,
		"--", clean)
	if output, err := say.CombinedOutput(); err != nil {
		return nil, "", fmt.Errorf("media: say failed (%s): %w", strings.TrimSpace(string(output)), err)
	}

	ff := exec.CommandContext(ctx, p.FFmpeg,
		"-hide_banner", "-loglevel", "error", "-y",
		"-i", aiff,
		"-c:a", "libmp3lame", "-b:a", "64k", "-ar", "22050", "-ac", "1",
		out)
	if output, err := ff.CombinedOutput(); err != nil {
		return nil, "", fmt.Errorf("media: ffmpeg failed (%s): %w", strings.TrimSpace(string(output)), err)
	}

	data, err := os.ReadFile(out)
	if err != nil {
		return nil, "", fmt.Errorf("media: reading synthesised audio: %w", err)
	}
	if len(data) == 0 {
		return nil, "", errors.New("media: synthesis produced an empty file")
	}
	return data, p.AudioFormat, nil
}

// NewTTS selects a provider by name. An empty name picks the only one that can
// work with no credentials, so a fresh clone can import content immediately.
func NewTTS(provider, voice, ffmpegPath string) (TTSProvider, error) {
	switch provider {
	case "", "say":
		return NewSayProvider(voice, ffmpegPath)
	case "none":
		return nil, ErrTTSUnavailable
	default:
		// A named cloud provider is expected to be registered here when its
		// credentials exist. Failing with the name is more useful than falling
		// back silently to a different voice.
		return nil, fmt.Errorf("media: no provider registered under TTS_PROVIDER=%q", provider)
	}
}

// EnsureAudio returns the key for a clip, generating and storing it when absent.
// The generated bool distinguishes "synthesised now" from "already present", which
// is what makes an import report meaningful and idempotency testable.
func EnsureAudio(ctx context.Context, store Store, tts TTSProvider, text string) (key string, generated bool, err error) {
	if tts == nil {
		return "", false, ErrTTSUnavailable
	}
	if strings.TrimSpace(text) == "" {
		return "", false, errors.New("media: cannot ensure audio for empty text")
	}
	key = AudioKey(tts.Name(), tts.Voice(), TextForAudio(text), tts.Format())
	if store.Exists(key) {
		return key, false, nil
	}
	data, format, err := tts.Synthesize(ctx, text)
	if err != nil {
		return "", false, err
	}
	// The key was derived before synthesis; if the provider reports a different
	// container than advertised, the key would lie about the bytes.
	expected := AudioKey(tts.Name(), tts.Voice(), TextForAudio(text), format)
	if expected != key {
		return "", false, fmt.Errorf("media: provider format %q disagrees with the configured key", format)
	}
	if err := store.Put(ctx, key, data, ContentTypeFor(key)); err != nil {
		return "", false, err
	}
	return key, true, nil
}
